/**
 * Arabic.
 *
 * Coverage is the application chrome and every page's header: navigation,
 * titles, ledes, buttons, tabs, statuses and shared components. Deeper body
 * copy — marketplace hints, compliance explainers, developer prose — still
 * falls back to English by design; keys can be added here without touching a
 * single component.
 *
 * Register: plain modern Arabic, the way a product speaks and not the way a
 * textbook does. That means a few specific rules, because the failure mode here
 * is a translation that is technically correct and reads like a translation.
 *
 * - **No vowel marks.** Normal Arabic prose carries none, and a UI full of
 *   shadda and damma reads as pedantic. The exception is a mark that does real
 *   work — a passive that would otherwise read as active, or a doubled
 *   consonant that changes the word. Where one was needed, the sentence was
 *   rewritten instead so it doesn't need it.
 * - **Not word-for-word.** English idiom translated directly produces Arabic
 *   nobody says: "so nothing can run away from you" is not "فلا شيء يفلت منك",
 *   it is "فلا مفاجآت آخر الشهر". Translate the meaning.
 * - **Active voice, and name the actor.** "نخصم الاستخدام" over "يُخصم
 *   الاستخدام" — shorter, unambiguous without vowels, and it says who is doing
 *   it. This is also why the copy says "we" freely.
 * - **Shorter than the English.** Arabic that is longer than its source is
 *   usually a sign the sentence was carried across rather than rewritten.
 * - **No dialect.** The product serves six countries, so Egyptian colloquial
 *   is the wrong answer even in an Egypt-first product. Plain Arabic reads
 *   native everywhere; dialect only reads native in one place.
 *
 * Conventions:
 * - Telecom terms keep their Latin forms where that is what engineers say in
 *   Arabic too (SIP, API, webhook, MOS, SRTP).
 * - `{name}` placeholders are interpolated, so numbers and names stay outside
 *   the translated sentence.
 */
